    constexpr std::string_view kFixtureDir = FIXTURE_DIR;

    std::string readFile(const fs::path &path)
    {
        std::ifstream in(path, std::ios::binary);
        if (!in)
            return {};
        std::ostringstream ss;
        ss << in.rdbuf();
        return ss.str();
    }

    std::vector<fs::path> collectByExtension(const fs::path &dir,
                                             std::string_view ext)
    {
        std::vector<fs::path> result;
        if (!fs::exists(dir))
            return result;
        for (const auto &entry : fs::directory_iterator(dir))
        {
            if (entry.is_regular_file() &&
                entry.path().extension() == ext)
            {
                result.push_back(entry.path());
            }
        }
        std::sort(result.begin(), result.end());
        return result;
    }

    // Parse a source and return the JSON dump of the module.
    std::string parseAndDump(const std::string &fileName,
                             const std::string &source)
    {
        StringPool pool;
        ASTArena arena;
        DiagnosticEngine diag(&pool);
        TokenStream stream(std::vector<Token>{
            Token{TokenType::EOF_TOKEN, InternedString{},
                  SourceLocation{1, 1}}});
        ParserContext ctx(pool, arena, diag, stream);

        ModuleAST *module = parseFile(fileName, source, ctx);
        return dumpModule(module, pool);
    }

