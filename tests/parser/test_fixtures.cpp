/// @file tests/parser/test_fixtures.cpp
///
/// @brief Fixture-driven tests for the parser and the dumper.
///
/// ─── What this file tests ─────────────────────────────────────────────────
/// Two test cases, one per fixture directory:
///
///   [fixtures][good]  — for each `good/*.lucid`, parse the file, dump
///                       the AST to JSON, and compare against the
///                       sibling `*.json`. The `.json` file is generated
///                       by the `regen-fixtures` target, never hand-
///                       edited.
///
///   [fixtures][bad]   — for each `bad/*.lucid`, parse the file and
///                       compare the diagnostic codes against the
///                       sibling `*.expected`. The `.expected` file is
///                       hand-maintained.
///
/// ─── Fixture layout ───────────────────────────────────────────────────────
/// tests/fixtures/parser/
///   good/
///     empty.lucid
///     empty.json            (generated by regen-fixtures)
///     import.lucid
///     import.json
///     ...
///   bad/
///     missing-name.lucid
///     missing-name.expected (hand-written, one DiagCode per line)
///     ...
///
/// ─── Regeneration ─────────────────────────────────────────────────────────
/// When the parser or the dumper changes, the good/*.json files may need
/// to be regenerated. Run:
///
///   cmake --build build --target regen-fixtures
///
/// Then `git diff tests/fixtures/parser/good/` to review the changes.

