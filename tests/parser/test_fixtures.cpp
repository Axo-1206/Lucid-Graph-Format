    // Parse a source and return the sequence of diagnostic codes,
    // in the order they were reported.
    std::vector<std::string> parseAndCollectCodes(const std::string &fileName,
                                                  const std::string &source)
    {
        StringPool pool;
        ASTArena arena;
        DiagnosticEngine diag(&pool);
        TokenStream stream(std::vector<Token>{
            Token{TokenType::EOF_TOKEN, InternedString{},
                  SourceLocation{1, 1}}});
        ParserContext ctx(pool, arena, diag, stream);

        (void)parseFile(fileName, source, ctx);

        std::vector<std::string> codes;
        for (const auto &d : diag.all())
        {
            codes.push_back(codeToString(d.code));
        }
        return codes;
    }

    // Read the expected codes from a `.expected` file: one code per
    // line, blank lines and lines starting with `#` ignored.
    std::vector<std::string> readExpectedCodes(const fs::path &path)
    {
        std::vector<std::string> codes;
        std::ifstream in(path);
        std::string line;
        while (std::getline(in, line))
        {
            // Trim trailing whitespace and CR (for files edited on
            // Windows).
            while (!line.empty() &&
                   (line.back() == '\r' || line.back() == ' '))
            {
                line.pop_back();
            }
            if (line.empty())
                continue;
            if (line.front() == '#')
                continue;
            codes.push_back(line);
        }
        return codes;
    }

